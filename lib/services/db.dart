  Future<List<Map<String, dynamic>>> queryPyramidSummary() async {
    final rows = await queryCategories();
    // db.query()'s result is sqflite's own read-only list — sort a copy,
    // never the original (the exact defect query_categories_readonly_test
    // covers elsewhere).
    final sorted = List<Map<String, dynamic>>.from(rows)
      ..sort((a, b) =>
          (a[columnPosition] as int).compareTo(b[columnPosition] as int));

    final summary = <Map<String, dynamic>>[];
    for (final row in sorted) {
      final id = row[columnCategoryId] as int;
      final position = row[columnPosition] as int;
      final tier =
          position <= 3 ? 'foundational' : (position <= 5 ? 'essential' : 'peak');
      summary.add({
        'id': id,
        'name': row[columnCat] as String,
        'tier': tier,
        'essence': await getLatestEssenceForCategory(id),
      });
    }
    return summary;
  }

  /// D-150: the longest run of consecutive days, ending on the most recent
  /// day with any tasklog activity for this category, where at least one
  /// of that day's tasks was checked. Same "group by date, walk sorted
  /// dates" approach visualizations.dart's _loadStreaksData already uses
  /// for its longest-ever streak — this instead only cares about the
  /// *current, still-active* run, which is what a "you're on a streak"
  /// newsfeed item needs (an ended streak isn't news).
  Future<int> getCurrentStreak(String categoryName) async {
    final db = await database;
    final rows = await db.query(getTaskLogTable(),
        where: '$columnTLCategory = ?', whereArgs: [categoryName]);
    final Map<String, bool> dailyCompletion = {};
    for (final row in rows) {
      final date = row[columnTLTaskDate] as String;
      dailyCompletion[date] =
          (dailyCompletion[date] ?? false) || row[columnTLChecked] == 'true';
    }
    final sortedDates = dailyCompletion.keys.toList()..sort();
    int streak = 0;
    for (final date in sortedDates.reversed) {
      if (dailyCompletion[date] != true) break;
      streak++;
    }
    return streak;
  }

  /// D-150: writes one newsfeed item, silently skipped (INSERT OR IGNORE)
  /// if [dedupeKey] was already used — the mechanism that makes calling
  /// the generator repeatedly (every time the newsfeed screen opens) safe.
  /// D-154: now returns whether the row was actually inserted (`true`) or
  /// silently ignored as a duplicate (`false`) — sqflite's `insert()`
  /// returns `0` on an ignored conflict (confirmed against the real
  /// sqflite package, not assumed), which is what a caller needs to know
  /// whether this is a genuinely *new* item worth firing a local
  /// notification for.
  /// D-158: [createdAt] lets a caller place an item at a deliberate
  /// position in the feed's newest-first order rather than always "now"
  /// — the seeded welcome cards use this to stay apart from each other
  /// (see NewsfeedService._seedWelcomeCards).
  Future<bool> insertNewsfeedItem({
    required String type,
    required String title,
    required String body,
    int? categoryId,
    required String dedupeKey,
    DateTime? createdAt,
  }) async {
    final db = await database;
    final id = await db.insert(
      newsfeedItemTable,
      {
        columnNewsfeedType: type,
        columnNewsfeedTitle: title,
        columnNewsfeedBody: body,
        columnNewsfeedCategoryId: categoryId,
        columnNewsfeedCreated: (createdAt ?? DateTime.now()).toIso8601String(),
        columnNewsfeedDedupeKey: dedupeKey,
      },
      conflictAlgorithm: ConflictAlgorithm.ignore,
    );
    return id != 0;
  }

  /// D-150: one page of the newsfeed, newest first.
  Future<List<Map<String, dynamic>>> queryNewsfeedItems({
    required int limit,
    required int offset,
  }) async {
    final db = await database;
    return db.query(
      newsfeedItemTable,
      orderBy: '$columnNewsfeedCreated DESC, $columnNewsfeedId DESC',
