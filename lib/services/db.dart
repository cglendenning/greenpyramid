  /// D-166: the v16->v17 migration's own cleanup — deletes every essence
  /// row whose text is identical to the immediately-preceding row (by
  /// [columnEssenceCreated]) for the same category, collapsing a
  /// "restored"-tagged run of phantom duplicate versions down to just
  /// its first occurrence. A genuine text change is never touched — only
  /// consecutive, byte-identical repeats. Static and pure-relative-to-`db`
  /// so it's directly testable against a raw database, matching this
  /// file's established migration-testing convention.
  static Future<void> _collapseDuplicateEssenceVersions(Database db) async {
    final rows = await db.query(categoryEssenceTable,
        orderBy: '$columnEssenceCategoryId ASC, $columnEssenceCreated ASC');
    final byCategory = <int, List<Map<String, dynamic>>>{};
    for (final row in rows) {
      final categoryId = row[columnEssenceCategoryId] as int;
      (byCategory[categoryId] ??= []).add(row);
    }
    final idsToDelete = <int>[];
    for (final categoryRows in byCategory.values) {
      String? previousText;
      for (final row in categoryRows) {
        final text = row[columnEssenceText] as String;
        if (text == previousText) {
          idsToDelete.add(row[columnEssenceId] as int);
        } else {
          previousText = text;
        }
      }
    }
    if (idsToDelete.isEmpty) return;
    final placeholders = List.filled(idsToDelete.length, '?').join(',');
    await db.delete(categoryEssenceTable,
        where: '$columnEssenceId IN ($placeholders)', whereArgs: idsToDelete);
  }

  /// D-167: a database-level backstop for the same invariant D-166's
  /// application-level guard enforces — belt and suspenders, at the
  /// owner's own explicit request after the phantom-duplicate defect
  /// ("ensure that there are guard rails in place to prevent this data
  /// condition from ever occurring again"). insertCategoryEssence is
  /// today the *only* code path that writes to [categoryEssenceTable]
  /// (confirmed directly against the source), so this trigger is not
  /// closing a currently-reachable gap — it exists so that no future
  /// code path (a new service method, a migration, a direct query) can
  /// silently reintroduce this exact data condition by writing to the
  /// table without going through the guarded helper. `RAISE(IGNORE)`
  /// inside a `BEFORE INSERT` trigger silently skips just that one insert
  /// (no exception raised, no partial transaction to clean up) — the same
  /// "no-op, not an error" contract `insertCategoryEssence`'s own
  /// `ConflictAlgorithm.ignore`-style guard already has, so a future
  /// caller that bypasses the Dart helper still gets safe, silent
  /// behavior rather than a crash.
  static Future<void> _createEssenceDuplicateGuardTrigger(Database db) async {
    await db.execute('''
      CREATE TRIGGER IF NOT EXISTS trg_no_duplicate_essence
      BEFORE INSERT ON $categoryEssenceTable
      WHEN NEW.$columnEssenceText = (
        SELECT $columnEssenceText FROM $categoryEssenceTable
        WHERE $columnEssenceCategoryId = NEW.$columnEssenceCategoryId
        ORDER BY $columnEssenceCreated DESC, $columnEssenceId DESC
        LIMIT 1
      )
      BEGIN
        SELECT RAISE(IGNORE);
      END;
    ''');
  }

  /// D-062: a user whose old-flow setup was incomplete when this build
  /// lands starts the new Council setup fresh, discarding their partial
  /// rows. "Complete" is six categories existing **and** at least one
  /// task existing — anything less is incomplete. A user who meets the
  /// definition is untouched (D-002, D-034). Runs once, gated by the
  /// version bump to 8, so it never re-triggers for an account created
  /// after this migration already ran.
  static Future<void> applyV8Migration(Database db) async {
    final categoryCount = Sqflite.firstIntValue(
            await db.rawQuery('SELECT COUNT(*) FROM $categoryTable')) ??
        0;
    final taskCount = Sqflite.firstIntValue(
            await db.rawQuery('SELECT COUNT(*) FROM $taskTable')) ??
        0;
    final complete = categoryCount >= 6 && taskCount >= 1;
    if (complete) return;

    // Never silent at the data layer, per D-062's acceptance criteria.
    print('D-062: incomplete old-flow setup found ($categoryCount '
        'categories, $taskCount tasks) — discarding partial rows, '
        'starting the new Council setup fresh.');

    await db.delete(taskTable);
    await db.delete(taskLogTable);
    await db.delete(categoryTable);
  }

