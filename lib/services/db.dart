  }

  /// D-155: a cheap existence check by dedupeKey, used before doing any
  /// of the (comparatively expensive) per-category stat-gathering or the
  /// AI call itself for the newsfeed's daily article — so a day that
  /// already has its article never re-does that work just to have
  /// insertNewsfeedItem's own dedup silently discard the result at the
  /// very end.
  Future<bool> newsfeedItemExists(String dedupeKey) async {
    final db = await database;
    final rows = await db.query(newsfeedItemTable,
        where: '$columnNewsfeedDedupeKey = ?', whereArgs: [dedupeKey], limit: 1);
    return rows.isNotEmpty;
  }

  /// D-168: how many on-demand articles have already been generated
  /// today — [prefix] is the day's own `article-<date>-manual-` stem, so
  /// this only ever counts today's on-demand generations, never the
  /// automatic daily one (a different dedupeKey shape entirely) or a
  /// prior day's. Used to enforce the daily on-demand cap before doing
  /// any stat-gathering or AI call.
  Future<int> countNewsfeedItemsWithDedupeKeyPrefix(String prefix) async {
    final db = await database;
    final result = await db.rawQuery(
        'SELECT COUNT(*) FROM $newsfeedItemTable WHERE $columnNewsfeedDedupeKey LIKE ?',
        ['$prefix%']);
    return Sqflite.firstIntValue(result) ?? 0;
  }


  /// D-154: the 0-based rank of the item identified by [dedupeKey] within
  /// the same newest-first ordering [queryNewsfeedItems] pages through —
  /// how a notification tap can jump the newsfeed screen straight to a
  /// specific item (load pages up to and including this rank, then
  /// scroll to it) without paging through the entire history first.
  /// Returns null if no such item exists (e.g., its dedupeKey is stale).
  Future<int?> getNewsfeedItemPosition(String dedupeKey) async {
    final db = await database;
    final rows = await db.query(newsfeedItemTable,
        where: '$columnNewsfeedDedupeKey = ?', whereArgs: [dedupeKey], limit: 1);
    if (rows.isEmpty) return null;
    final target = rows.first;
    final targetCreated = target[columnNewsfeedCreated] as String;
    final targetId = target[columnNewsfeedId] as int;
    final result = await db.rawQuery(
        'SELECT COUNT(*) AS c FROM $newsfeedItemTable WHERE '
        '$columnNewsfeedCreated > ? OR ($columnNewsfeedCreated = ? AND $columnNewsfeedId > ?)',
        [targetCreated, targetCreated, targetId]);
    return Sqflite.firstIntValue(result) ?? 0;
  }

  /// D-028/D-061: appends a new essence version for a category (essences are
  /// versioned, never overwritten — D-061). D-166: a no-op — returns
  /// `false`, inserts nothing — when [essence] is identical to the
  /// category's current latest version. Found live: `SyncService
  /// .restoreFromCloud` called this unconditionally on every restore,
  /// manufacturing a brand-new "version" with the exact same text as
  /// before purely as a side effect of syncing — seven or more phantom
  /// "redefinitions" per category on one real account, none of them an
  /// actual change the user made. Guarding here, in the shared insert
  /// path, protects every caller uniformly (not just restoreFromCloud) —
  /// a version-history table recording the same value twice in a row is
  /// never meaningful, regardless of which caller triggered it. Returns
  /// `true` iff a new row was actually inserted, so a caller (the
  /// newsfeed's own notification path, for one) can tell whether a real
  /// change happened.
  Future<bool> insertCategoryEssence({
    required int categoryId,
    required String essence,
    String? sourceSessionId,
  }) async {
    final current = await getLatestEssenceForCategory(categoryId);
    if (current == essence) return false;
    final db = await database;
    await db.insert(categoryEssenceTable, {
      columnEssenceCategoryId: categoryId,
      columnEssenceText: essence,
      columnEssenceCreated: DateTime.now().toIso8601String(),
      columnEssenceSourceSession: sourceSessionId,
    });
    return true;
  }

