    }
    await raw.close();

    final upgraded = await db.database;
    final rows = await upgraded.query(DatabaseHelper.newsfeedItemTable);

    expect(rows, isEmpty,
        reason: "the chain's final step (D-168's v19->v20) is an "
            'unconditional full wipe, so nothing of any type survives '
            'reaching the current version from this starting point');
  });

  test('D-166: the v16->v17 migration collapses consecutive same-text '
      'essence rows per category (phantom versions manufactured by every '
      "past call to SyncService.restoreFromCloud, before "
      'insertCategoryEssence was guarded) down to just the first '
      'occurrence, leaving a genuine change untouched, and clears '
      'type=essence newsfeed rows again so they regenerate from the '
      'corrected history', () async {
    final path = '${tempDir.path}/LifeOps.db';
    final raw = await databaseFactory.openDatabase(
      path,
      options: OpenDatabaseOptions(
        version: 16,
        onCreate: (db, version) => _createV12SchemaWithEssence(db),
      ),
    );
    Future<void> insertEssence(int categoryId, String text, String created) =>
        raw.insert('category_essence', {
          'categoryid': categoryId,
          'essence': text,
          'created': created,
          'source_session_id': 'restored',
        });
    // Exactly the shape found live: several "restored" duplicates of the
    // same text, a genuine change, then more duplicates of the new text.
    await insertEssence(1, 'Reconnect with your essence', '2026-09-11T11:13:32');
    await insertEssence(1, 'Reconnect with your essence', '2026-09-11T11:27:15');
    await insertEssence(1, 'Reconnect with your essence', '2026-09-11T11:29:33');
    await insertEssence(1, 'Something new.', '2026-09-12T06:05:39');
    await insertEssence(1, 'Something new.', '2026-09-12T06:58:20');
    await raw.insert(DatabaseHelper.newsfeedItemTable, {
      DatabaseHelper.columnNewsfeedType: 'essence',
      DatabaseHelper.columnNewsfeedTitle: 'essence title',
      DatabaseHelper.columnNewsfeedBody: 'essence body',
      DatabaseHelper.columnNewsfeedCreated: DateTime.now().toIso8601String(),
      DatabaseHelper.columnNewsfeedDedupeKey: 'essence-key',
    });
    await raw.close();

    final upgraded = await db.database;
    final essenceRows =
        await upgraded.query('category_essence', orderBy: 'created ASC');
    expect(essenceRows.length, 2,
        reason: 'both runs of consecutive duplicates collapse to their '
            'first occurrence; the genuine change between them survives');
    expect(essenceRows[0]['essence'], 'Reconnect with your essence');
    expect(essenceRows[1]['essence'], 'Something new.');

    final newsfeedRows = await upgraded.query(DatabaseHelper.newsfeedItemTable);
    expect(newsfeedRows, isEmpty,
        reason: 'type=essence newsfeed rows are cleared again so they '
            'regenerate from the corrected history');
  });

  test('D-167: the v17->v18 migration installs the duplicate-guard '
      'trigger on an existing database — an account already upgraded to '
      'v17 (and therefore already missing the trigger, since it was only '
      "created in applyV7Schema for a fresh install) gets it retroactively",
      () async {
    final path = '${tempDir.path}/LifeOps.db';
    final raw = await databaseFactory.openDatabase(
      path,
      options: OpenDatabaseOptions(
        version: 17,
        onCreate: (db, version) => _createV12SchemaWithEssence(db),
      ),
    );
    await raw.insert('category_essence', {
      'categoryid': 1,
      'essence': 'Stay strong.',
      'created': DateTime.now().toIso8601String(),
    });
    await raw.close();

    final upgraded = await db.database;
    // The trigger now exists and blocks a same-text insert, even though
    // this database was created before D-167 shipped.
    await upgraded.insert('category_essence', {
      'categoryid': 1,
      'essence': 'Stay strong.',
      'created': DateTime.now().toIso8601String(),
    });
    final rows =
        await upgraded.query('category_essence', where: 'categoryid = ?', whereArgs: [1]);
    expect(rows.length, 1,
        reason: 'the v17->v18 migration installed the trigger, so the '
            'duplicate insert above was silently skipped');
  });

  test('D-168: upgrading from v18 applies every migration in the chain '
      'without error — this directive originally retired the two '
      "generic welcome cards on their own (v18->v19); by the current "
      "version, D-168's own later full wipe (v19->v20) leaves nothing "
      'of any type, which is expected and covered by its own dedicated '
      'test further below. The v19 step\'s own "only welcome, nothing '
      'else" behavior is exercised directly by the dedicated v19->v20 '
      'test\'s own predecessor state, not re-isolated here.', () async {
    final path = '${tempDir.path}/LifeOps.db';
    final raw = await databaseFactory.openDatabase(
      path,
      options: OpenDatabaseOptions(
        version: 18,
        onCreate: (db, version) => _createV12SchemaWithEssence(db),
      ),
    );
    for (final type in ['welcome', 'essence', 'streak', 'article']) {
      await raw.insert(DatabaseHelper.newsfeedItemTable, {
        DatabaseHelper.columnNewsfeedType: type,
        DatabaseHelper.columnNewsfeedTitle: '$type title',
        DatabaseHelper.columnNewsfeedBody: '$type body',
        DatabaseHelper.columnNewsfeedCreated: DateTime.now().toIso8601String(),
        DatabaseHelper.columnNewsfeedDedupeKey: '$type-key',
      });
    }
    await raw.close();

    final upgraded = await db.database;
    final rows = await upgraded.query(DatabaseHelper.newsfeedItemTable);

    expect(rows, isEmpty,
        reason: "the chain's final step (D-168's v19->v20) is an "
            'unconditional full wipe, so nothing of any type survives '
            'reaching the current version from this starting point');
  });

  test('D-168 (backfill): the v19->v20 migration unconditionally wipes '
      'every newsfeed_item row — owner: "I also need you to clean up my '
      'database because I still have cards in there that were generated '
      'before this change." Every card, of every type, regenerates fresh '
      'under everything the newsfeed accumulated across D-154 through '
      "D-168, not just whichever single round each prior narrow "
      'migration targeted', () async {
    final path = '${tempDir.path}/LifeOps.db';
    final raw = await databaseFactory.openDatabase(
      path,
      options: OpenDatabaseOptions(
        version: 19,
        onCreate: (db, version) => _createV12SchemaWithEssence(db),
      ),
    );
    for (final type in ['sample', 'essence', 'streak', 'article']) {
      await raw.insert(DatabaseHelper.newsfeedItemTable, {
        DatabaseHelper.columnNewsfeedType: type,
        DatabaseHelper.columnNewsfeedTitle: '$type title',
        DatabaseHelper.columnNewsfeedBody: '$type body',
        DatabaseHelper.columnNewsfeedCreated: DateTime.now().toIso8601String(),
        DatabaseHelper.columnNewsfeedDedupeKey: '$type-key',
      });
    }
    await raw.close();

    final upgraded = await db.database;
    final rows = await upgraded.query(DatabaseHelper.newsfeedItemTable);

    expect(rows, isEmpty,
        reason: 'this migration is a full, unconditional wipe — no row '
            'of any type survives it');
  });
}
